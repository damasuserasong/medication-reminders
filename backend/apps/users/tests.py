class TestStayingSignedIn:
    def test_refresh_returns_a_working_access_token(self, signed_in):
        response = signed_in.post(REFRESH_URL)

        assert response.status_code == status.HTTP_200_OK
        assert 'refresh' not in response.data
        fresh = APIClient()
        fresh.credentials(HTTP_AUTHORIZATION=f"Bearer {response.data['access']}")
        assert fresh.get(ME_URL).status_code == status.HTTP_200_OK

    def test_refresh_without_a_cookie_is_refused(self, api_client, db):
        assert api_client.post(REFRESH_URL).status_code == status.HTTP_401_UNAUTHORIZED

    def test_a_used_refresh_token_cannot_be_used_again(self, signed_in):
        old_cookie = signed_in.cookies[COOKIE_NAME].value
        signed_in.post(REFRESH_URL)

        replay = APIClient()
        replay.cookies[COOKIE_NAME] = old_cookie

        assert replay.post(REFRESH_URL).status_code == status.HTTP_401_UNAUTHORIZED

    def test_still_signed_in_the_next_day_when_active(self, user, signed_in):
        now = sessions._now()
        with mock.patch.object(sessions, '_now', return_value=now + 23 * 3600):
            assert signed_in.post(REFRESH_URL).status_code == status.HTTP_200_OK

    def test_ends_after_twenty_four_hours_of_inactivity(self, signed_in):
        now = sessions._now()
        with mock.patch.object(sessions, '_now', return_value=now + 25 * 3600):
            response = signed_in.post(REFRESH_URL)

        assert response.status_code == status.HTTP_401_UNAUTHORIZED

    def test_renewing_does_not_extend_the_seven_day_limit(self, user):
        original = sessions.start_session(user)

        renewed = sessions.renew_session(str(original))

        assert renewed['exp'] == original['exp']

    def test_ends_after_seven_days_however_active(self, user):
        token = sessions.start_session(user)
        token.payload['exp'] = sessions._now() - 1

        with pytest.raises(Exception):
            sessions.renew_session(str(token))

    def test_a_disabled_account_cannot_renew(self, user, signed_in):
        user.is_active = False
        user.save()

        assert signed_in.post(REFRESH_URL).status_code == status.HTTP_401_UNAUTHORIZED

    def test_session_survives_without_server_memory(self, user):
        """Nothing about a session is held in the process: a new client with
        only the cookie value, as after a restart, still renews it."""
        cookie = str(sessions.start_session(user))

        restarted = APIClient()
        restarted.cookies[COOKIE_NAME] = cookie

        assert restarted.post(REFRESH_URL).status_code == status.HTTP_200_OK


class TestLogout:
    def test_ends_the_session_on_this_device(self, signed_in):
        cookie = signed_in.cookies[COOKIE_NAME].value

